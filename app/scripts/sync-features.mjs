#!/usr/bin/env node
// app/config/feature-registry.json is the sole manually edited module catalog.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const app = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const root = resolve(app, '..')
const data = JSON.parse(readFileSync(join(app, 'config/feature-registry.json'), 'utf8'))
const checking = process.argv.includes('--check')
const errors = []
const requireField = (condition, message) => { if (!condition) errors.push(message) }
requireField(data.schemaVersion === 1, 'Unsupported registry version')
requireField(Array.isArray(data.modules), 'modules must be an array')
const modules = Array.isArray(data.modules) ? data.modules : []
const keys = new Set()
const router = readFileSync(join(app, 'web/src/router/index.ts'), 'utf8')
const webRoutes = new Set([...router.matchAll(/path:\s*['"]([^'"]+)['"]/g)].map(match => match[1]))
const pages = JSON.parse(readFileSync(join(app, 'mobile/src/pages.json'), 'utf8'))
const mobileRoutes = new Set(pages.pages.map(page => page.path))

for (const m of modules) {
  const key = m.type + ':' + m.code
  requireField(!keys.has(key), 'Duplicate module key: ' + key)
  keys.add(key)
  requireField(/^[a-z][a-z0-9-]*$/.test(m.code || ''), 'Invalid code: ' + key)
  requireField(typeof m.name === 'string' && m.name.trim().length > 0, 'Missing name: ' + key)
  requireField(typeof m.description === 'string' && m.description.trim().length > 0, 'Missing description: ' + key)
  requireField(typeof m.enabled === 'boolean', 'Missing enabled flag: ' + key)
  requireField(Number.isInteger(m.sortOrder), 'Invalid sortOrder: ' + key)
  if (m.type === 'feature') {
    requireField(m.status === 'implemented', 'Only main-implemented features can be registered: ' + key)
    requireField(m.visibility === 'admin' || m.visibility === 'authenticated', 'Invalid visibility: ' + key)
    requireField(typeof m.visibleInNav === 'boolean', 'Invalid visibleInNav: ' + key)
    requireField(typeof m.webRoute === 'string' && webRoutes.has(m.webRoute), 'Missing Web route: ' + key)
    requireField(typeof m.backendPackage === 'string' &&
      existsSync(join(app, 'backend/src/main/java/com/matrix/prp', m.backendPackage || '_missing_')),
      'Missing backend module package: ' + key)
    requireField(m.mobileRoute === null || mobileRoutes.has(m.mobileRoute), 'Missing Mobile route: ' + key)
  } else {
    requireField(m.type === 'domain', 'Unknown module type: ' + key)
    requireField(m.status === 'category' && m.webRoute === null && m.mobileRoute === null,
      'Domains are categories, not shipped pages: ' + key)
    requireField(m.visibleInNav === false, 'Domain cannot be in Web menu: ' + key)
  }
}
const features = modules.filter(m => m.type === 'feature')
const domains = modules.filter(m => m.type === 'domain')
requireField(features.length > 0 && features.some(m => m.code === 'dashboard'), 'Missing dashboard or all features')
if (errors.length > 0) {
  for (const error of errors) console.error('Feature registry: ' + error)
  process.exit(1)
}

const web = '// Generated by app/scripts/sync-features.mjs. Do not edit manually.\n'
  + 'export const features = ' + JSON.stringify(features.map(({code, name, sortOrder, enabled, status, webRoute, visibility, visibleInNav}) =>
    ({code, name, sortOrder, enabled, status, webRoute, visibility, visibleInNav})), null, 2) + ' as const\n'
const tick = String.fromCharCode(96)
const fenced = value => tick + value + tick
const doc = [
  '# Matrix PRP 功能目录（自动生成）',
  '',
  '> 由 ' + fenced('app/config/feature-registry.json') + ' 生成。运行 ' + fenced('node app/scripts/sync-features.mjs') + ' 更新，请勿手工编辑。',
  '> 已实现仅表示代码进入 main，不等于生产环境或 iPhone 实机验收完成。未合并的 AI PR #9 不算已实现。',
  '',
  '## 已实现的功能',
  '',
  '| 编码 | 名称 | Web 入口 | Mobile 入口 | 权限范围 | 后端模块 |',
  '| --- | --- | --- | --- | --- | --- |',
  ...features.map(m => '| ' + fenced(m.code) + ' | ' + m.name + ' | ' +
    fenced(m.webRoute ?? '—') + ' | ' + fenced(m.mobileRoute ?? '—') + ' | ' +
    (m.visibility === 'admin' ? '仅管理员' : '登录用户') + ' | ' + fenced(m.backendPackage) + ' |'),
  '',
  '## 业务资源域（仅分类，不代表已有独立功能）',
  '',
  '| 编码 | 名称 | 说明 |',
  '| --- | --- | --- |',
  ...domains.map(m => '| ' + fenced(m.code) + ' | ' + m.name + ' | ' + m.description + ' |'),
  '',
  '## 使用说明',
  '',
  '- 登录和数据隔离为基础服务；PWA、视频存储与通知投递为模块内部能力。',
  '- Web 菜单由生成的 ' + fenced('app/web/src/generated/features.ts') + ' 驱动，显式路由由校验脚本核实。',
  '- Mobile 只登记已存在的页面，没有入口不意味着该功能已在移动端实现。',
  '- 详细维护方式参阅 ' + fenced('app/docs/technical/feature-registry.md') + '。',
  '',
].join('\n')
const generated = [
  [join(app, 'backend/src/main/resources/feature-registry.json'), JSON.stringify(data, null, 2) + '\n'],
  [join(app, 'web/src/generated/features.ts'), web],
  [join(app, 'docs/features/FEATURES.md'), doc],
]
for (const [path, content] of generated) {
  if (checking) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== content) {
      errors.push('Outdated generated file: ' + path.slice(root.length + 1))
    }
  } else {
    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(path, content, 'utf8')
  }
}
if (errors.length) {
  for (const error of errors) console.error('Feature registry: ' + error)
  process.exitCode = 1
} else {
  console.log(checking ? 'Feature registry validated' : 'Feature registry files generated')
}
